bool get_permissive_hold(uint16_t keycode, keyrecord_t *record) {
    switch (keycode) {
        case CL_MEH:
            return true;
        default:
            return false;
    }
}

// Lighting: solid white at ~75% brightness, applied on every power-on.
// The _noeeprom calls don't save anything, so Fn+RGB changes last only until the next restart.
void keyboard_post_init_user(void) {
    rgb_matrix_enable_noeeprom();
    rgb_matrix_mode_noeeprom(RGB_MATRIX_SOLID_COLOR);
    rgb_matrix_sethsv_noeeprom(0, 0, RGB_MATRIX_MAXIMUM_BRIGHTNESS * 3 / 4); // hue 0, saturation 0 = white
}